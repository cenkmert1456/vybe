def emit(name, d):
    lines = [f"const {name}: PartialDict = {{"]
    for k, v in d.items():
        lines.append(f"  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)},")
    lines.append("};")
    return "\n".join(lines)

